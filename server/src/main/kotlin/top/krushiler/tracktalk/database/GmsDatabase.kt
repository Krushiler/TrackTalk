import org.jetbrains.exposed.v1.jdbc.transactions.suspendTransaction
import org.jetbrains.exposed.v1.jdbc.transactions.transaction

internal class GmsDatabase(databaseUrl: String?) {
    private val database = connectGmsDatabase(databaseUrl)

    suspend fun <T> transaction(block: suspend () -> T): T = withContext(Dispatchers.IO) {
        suspendTransaction(db = database) {
            block()
        }
    }
}

internal fun connectGmsDatabase(databaseUrl: String?): Database {
    val target = if (databaseUrl.isNullOrBlank()) h2Target() else postgresTarget(databaseUrl)
    GmsDialect.postgres = target.postgres
    val database = Database.connect(
        url = target.url,
        driver = target.driver,
        user = target.user,
        password = target.password,
    )
    transaction(database) {
        statements(target.postgres).forEach { statement -> exec(statement) }
    }
    return database
}

private data class JdbcTarget(
    val url: String,
    val driver: String,
    val user: String,
    val password: String,
    val postgres: Boolean,
)

private fun h2Target(): JdbcTarget = JdbcTarget(
    url = "jdbc:h2:mem:gms-${UUID.randomUUID()};MODE=PostgreSQL;DB_CLOSE_DELAY=-1;DATABASE_TO_LOWER=TRUE",
    driver = "org.h2.Driver",
    user = "sa",
    password = "",
    postgres = false,
)

private fun postgresTarget(raw: String): JdbcTarget {
    if (raw.startsWith("jdbc:postgresql:")) {
        return JdbcTarget(
            url = raw,
            driver = "org.postgresql.Driver",
            user = "",
            password = "",
            postgres = true,
        )
    }
    val withoutDriver = raw
        .removePrefix("postgresql+asyncpg://")
        .removePrefix("postgresql+psycopg://")
        .removePrefix("postgresql+pg8000://")
        .removePrefix("postgresql://")
        .removePrefix("postgres://")
    val uri = URI("postgresql://$withoutDriver")
    val userInfo = uri.rawUserInfo?.split(":", limit = 2).orEmpty()
    val user = userInfo.getOrNull(0)?.decode()?.ifBlank { "postgres" } ?: "postgres"
    val password = userInfo.getOrNull(1)?.decode().orEmpty()
    val host = uri.host ?: "localhost"
    val port = if (uri.port == -1) 5432 else uri.port
    val database = uri.path.removePrefix("/").ifBlank { "gms" }
    val query = uri.rawQuery?.let { "?$it" }.orEmpty()
    return JdbcTarget(
        url = "jdbc:postgresql://$host:$port/$database$query",
        driver = "org.postgresql.Driver",
        user = user,
        password = password,
        postgres = true,
    )
}

private fun String.decode(): String = URLDecoder.decode(this, StandardCharsets.UTF_8)

